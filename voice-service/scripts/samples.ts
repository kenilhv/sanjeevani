// Writes a sample request + response for every actor method in contracts.md §2, taken from the
// placeholder backend, plus the events each call emits. Hand samples/ to whoever builds the real
// actors so their return values and events match what the screens and voice already use.
//   npm run samples

import { mkdir, writeFile } from "node:fs/promises"
import { mockBackend } from "../src/actors/mock.ts"
import { subscribe } from "../src/events.ts"

const OUT = new URL("../samples/", import.meta.url)
await mkdir(OUT, { recursive: true })

let emitted: unknown[] = []
subscribe((e) => {
  if (e.kind !== "vitals" || emitted.length < 2) emitted.push(Object.fromEntries(Object.entries(e).filter(([k]) => k !== "id")))
})

// Order follows the night so each response reflects a realistic moment.
const CALLS: [string, string, Record<string, unknown>][] = [
  ["unit:floor-4west", "reset", {}],
  ["unit:floor-4west", "setClock", { simTime: "19:00", speed: 1 }],
  ["unit:floor-4west", "assign", { podId: "pod-a", nurseId: "maya" }],
  ["pod:pod-a", "signIn", { nurseId: "maya" }],
  ["unit:floor-4west", "setClock", { simTime: "23:30", speed: 1 }],
  ["pod:pod-a", "voiceNote", { transcript: "Room 6, gave zolpidem 5 milligrams for sleep.", nurseId: "maya", simTime: "23:30" }],
  ["patient:room-8", "patientRequest", { text: "I feel shaky.", simTime: "02:00" }],
  ["unit:floor-4west", "setClock", { simTime: "03:31", speed: 1 }],
  ["patient:room-2", "addVital", { type: "bp_systolic", value: 128, simTime: "03:00" }],
  ["patient:room-2", "addVital", { type: "bp_systolic", value: 112, simTime: "03:30" }],
  ["patient:room-2", "addVital", { type: "bp_systolic", value: 98, simTime: "04:00" }],
  ["unit:floor-4west", "setClock", { simTime: "06:45", speed: 1 }],
  ["pod:pod-a", "signOut", { nurseId: "maya" }],
  ["pod:pod-a", "signIn", { nurseId: "jordan" }],
  ["pod:pod-a", "brief", { nurseId: "jordan" }],
  ["pod:pod-a", "ask", { question: "Did Room 4's pain improve?", nurseId: "jordan" }],
  ["patient:room-4", "ask", { question: "Did pain improve?", askedBy: "jordan" }],
  ["patient:room-4", "readback", { text: "Room 4: 3am potassium given late, confirmed. Pain down to 3.", nurseId: "jordan" }],
  ["patient:room-6", "readback", { text: "Room 6 is stable.", nurseId: "jordan" }],
  ["unit:floor-4west", "markReadback", { room: "room-4", ok: true }],
  ["patient:room-6", "getState", {}],
  ["pod:pod-a", "getState", {}],
  ["unit:floor-4west", "getState", {}],
]

const index: string[] = []
for (const [actorId, method, input] of CALLS) {
  emitted = []
  let response: unknown
  try {
    response = await mockBackend.call(actorId, method, input)
  } catch (err) {
    response = { error: (err as Error).message }
  }
  const file = `${actorId.replace(":", "_")}.${method}.json`
  const body = { actor: actorId, method, input, response, emits: emitted }
  await writeFile(new URL(file, OUT), JSON.stringify(body, null, 2) + "\n")
  index.push(`- \`${actorId}.${method}\` → [${file}](${file})`)
}

await writeFile(
  new URL("README.md", OUT),
  `# Sample actor responses\n\nGenerated by \`npm run samples\` from the placeholder backend (src/actors/mock.ts).\n` +
    `Each file has the input, the response, and the frontend events (contracts.md §4) the call emitted.\n\n${index.join("\n")}\n`,
)
console.log(`Wrote ${CALLS.length} samples to samples/`)
process.exit(0)
